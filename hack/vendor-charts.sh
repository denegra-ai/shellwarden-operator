#!/bin/sh
# Re-vendor the upstream charts at OPENSHELL_VERSION and apply the default-value changes listed
# in helm-charts/PATCHES.md. Runs inside the tools image (make vendor), which has helm, yq, curl.
#
# The result is committed, so an upstream bump is a reviewed diff of what the operator ships.
set -eu

: "${OPENSHELL_VERSION:?}"
: "${GATEWAY_DIGEST:?}" "${SUPERVISOR_DIGEST:?}" "${SANDBOX_RUNTIME_DIGEST:?}" "${SANDBOX_BASE_DIGEST:?}"

out=helm-charts
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# The gateway chart, as NVIDIA publishes it.
helm pull oci://ghcr.io/nvidia/openshell/helm-chart --version "$OPENSHELL_VERSION" --untar -d "$tmp"
rm -rf "$out/openshell"
mv "$tmp/helm-chart" "$out/openshell"

# The workspace chart is not published on its own; take it from the release tag.
raw="https://raw.githubusercontent.com/NVIDIA/OpenShell/v$OPENSHELL_VERSION/deploy/helm/openshell-workspace"
rm -rf "$out/openshell-workspace"
mkdir -p "$out/openshell-workspace/templates"
for f in Chart.yaml values.yaml; do
  curl -fsSL "$raw/$f" -o "$out/openshell-workspace/$f"
done
for f in _helpers.tpl networkpolicy.yaml role.yaml rolebinding.yaml serviceaccount.yaml; do
  curl -fsSL "$raw/templates/$f" -o "$out/openshell-workspace/templates/$f"
done

# PATCHES.md, 1: anonymous telemetry to NVIDIA off by default.
# PATCHES.md, 2: every image by digest, so a mirror needs only global.image.registry.
# Edited line by line (yq would rewrite the whole file's layout); yq then checks the result.
values="$out/openshell/values.yaml"
awk -v gw="$GATEWAY_DIGEST" -v sup="$SUPERVISOR_DIGEST" -v rt="$SANDBOX_RUNTIME_DIGEST" -v sb="$SANDBOX_BASE_DIGEST" '
  /^[A-Za-z]/ { section = $1; sub(":.*", "", section) }
  /^    digest: ""$/ {
    d = (section == "gateway") ? gw : (section == "supervisor") ? sup : (section == "sandboxRuntime") ? rt : (section == "sandbox") ? sb : ""
    if (d != "") { print "    digest: \"" d "\""; next }
  }
  section == "server" && /^  telemetryEnabled: true$/ { print "  telemetryEnabled: false"; next }
  { print }
' "$values" > "$tmp/values.yaml"
mv "$tmp/values.yaml" "$values"
check() { [ "$(yq "$1" "$values")" = "$2" ] || { echo "$values: $1 is not $2" >&2; exit 1; }; }
check .server.telemetryEnabled false
check .gateway.image.digest "$GATEWAY_DIGEST"
check .supervisor.image.digest "$SUPERVISOR_DIGEST"
check .sandboxRuntime.image.digest "$SANDBOX_RUNTIME_DIGEST"
check .sandbox.image.digest "$SANDBOX_BASE_DIGEST"

# PATCHES.md, 4: the OpenShift copy. The same chart with the pinned pod user and group IDs
# deleted from its defaults, as NVIDIA's ci/values-openshift-scc.yaml overlay removes them, so
# restricted-v2 assigns the namespace's range. watches-openshift.yaml uses it. (helm-operator's
# overrideValues cannot delete a value: "null" arrives as the string "null".) Generated: yq
# rewrites the layout of this copy's values.yaml.
rm -rf "$out/openshell-openshift"
cp -R "$out/openshell" "$out/openshell-openshift"
yq -i '
  del(.podSecurityContext.fsGroup) |
  del(.securityContext.runAsUser) |
  del(.supervisor.podSecurityContext.runAsUser) |
  del(.supervisor.podSecurityContext.runAsGroup) |
  del(.supervisor.podSecurityContext.fsGroup)
' "$out/openshell-openshift/values.yaml"
printf '# GENERATED by hack/vendor-charts.sh from ../openshell: see ../PATCHES.md, item 4.\n' \
  | cat - "$out/openshell-openshift/values.yaml" > "$tmp/v" && mv "$tmp/v" "$out/openshell-openshift/values.yaml"

# PATCHES.md, 3: the workspace chart's version is 0.0.0 in the repository; name the release.
yq -i ".version = \"$OPENSHELL_VERSION\" | .appVersion = \"$OPENSHELL_VERSION\"" \
  "$out/openshell-workspace/Chart.yaml"

echo "vendored OpenShell $OPENSHELL_VERSION charts into $out/"
